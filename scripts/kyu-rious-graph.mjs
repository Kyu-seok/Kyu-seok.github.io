// Fetches kyu-rious's graph.json and writes src/content/kyu-rious.gen.ts, which the notes card and the Fun
// card read. Runs before every dev server and build (package.json pre-scripts); pages.yml also rebuilds daily
// so new lessons appear within a day. Any failure exits non-zero: the build fails and Pages keeps the last
// good deploy. The page itself never fetches this (PRODUCT.md: one network call, to ask.code-bite.com).
import { writeFileSync } from 'node:fs';

const BASE = 'https://kyu-seok.github.io/kyu-rious/';
const OUT = new URL('../src/content/kyu-rious.gen.ts', import.meta.url);

function fail(msg) {
  console.error(`kyu-rious-graph: ${msg}`);
  process.exit(1);
}

let graph;
try {
  const res = await fetch(`${BASE}graph.json`, { signal: AbortSignal.timeout(15000) });
  if (!res.ok) fail(`graph.json returned HTTP ${res.status}`);
  graph = await res.json();
} catch (err) {
  fail(`could not fetch graph.json: ${err.message}`);
}

if (!Array.isArray(graph?.nodes)) fail('graph.json has no nodes array');
for (const n of graph.nodes) {
  for (const k of ['id', 'kind', 'topic', 'title', 'summary', 'url']) {
    if (typeof n[k] !== 'string' || n[k] === '') fail(`node ${JSON.stringify(n.id)} lacks ${k}`);
  }
}

const topics = {};
for (const n of graph.nodes.filter((n) => n.kind === 'topic')) {
  topics[n.topic] = { title: n.title, summary: n.summary, url: new URL(n.url, BASE).href, lessons: [], refs: 0 };
}
if (Object.keys(topics).length === 0) fail('graph.json has no topics');
for (const n of [...graph.nodes].sort((a, b) => a.id.localeCompare(b.id))) {
  const t = topics[n.topic];
  if (!t && n.kind !== 'topic') fail(`node ${n.id} belongs to unknown topic ${n.topic}`);
  if (n.kind === 'lesson') t.lessons.push({ title: n.title, url: new URL(n.url, BASE).href });
  else if (n.kind === 'reference') t.refs++;
}

const src = `// Generated by scripts/kyu-rious-graph.mjs from ${BASE}graph.json. Do not edit; not committed.
export const STUDY_TOPICS = ${JSON.stringify(topics, null, 2)} as const;

export type StudyTopicSlug = keyof typeof STUDY_TOPICS;
`;
writeFileSync(OUT, src);
const lessons = Object.values(topics).reduce((s, t) => s + t.lessons.length, 0);
console.log(`kyu-rious-graph: ${Object.keys(topics).length} study topics, ${lessons} lessons`);
